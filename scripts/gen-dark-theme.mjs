// Generates app/dark-theme.css: the dark colour theme.
//
// The app is styled with Tailwind colour utilities (bg-indigo-50, text-indigo-950, bg-white ...), which all read CSS
// variables such as --color-indigo-50. Dark mode swaps each used palette end for end (50 <-> 950, 100 <-> 900, ...) and
// replaces white with a deep indigo, so every light-on-dark and dark-on-light pairing in the design keeps its contrast
// relationship, with no per-component dark: classes to maintain.
//
//   node scripts/gen-dark-theme.mjs        (rewrites app/dark-theme.css from Tailwind's own palette)
import { readFileSync, writeFileSync } from "node:fs";

const theme = readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const PALETTES = ["indigo", "slate", "amber", "red", "sky", "green"];
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

const value = (palette, step) => {
  const m = theme.match(new RegExp(`--color-${palette}-${step}:\\s*([^;]+);`));
  if (!m) throw new Error(`missing --color-${palette}-${step} in tailwindcss/theme.css`);
  return m[1].trim();
};

const lines = [];
for (const palette of PALETTES) {
  for (const step of STEPS) {
    const mirror = step === 50 ? 950 : step === 950 ? 50 : 1000 - step;
    lines.push(`  --color-${palette}-${step}: ${value(palette, mirror)};`);
  }
}

const css = `/* GENERATED by scripts/gen-dark-theme.mjs: do not edit by hand. See that file for how it works. */
:root[data-theme="dark"] {
  color-scheme: dark;
  --foreground: #e0e7ff;
  --color-white: oklch(21% 0.05 281);
  --wheel-pointer: #e0e7ff;
${lines.join("\n")}
}

:root[data-theme="dark"] body {
  background: linear-gradient(135deg, #1e1b4b 0%, #2e1065 50%, #172554 100%) fixed;
}
`;

writeFileSync("app/dark-theme.css", css);
console.log(`wrote app/dark-theme.css (${PALETTES.length} palettes)`);
